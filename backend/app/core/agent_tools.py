# TOOL 4: Report Generator - create DOCX
# ============================================================
async def report_generator(report_data: Dict[str, Any], template: str = "inspection_analysis") -> Dict[str, Any]:
    """Generate professional DOCX report from structured data."""
    doc = Document()
    
    # Base Style
    style = doc.styles['Normal']
    style.font.name = 'Calibri'
    style.font.size = Pt(11)
    
    # Title
    title = doc.add_heading('Inspection Analysis Report', 0)
    title.alignment = WD_ALIGN_PARAGRAPH.CENTER
    
    # Metadata table
    table = doc.add_table(rows=6, cols=2, style='Table Grid')
    meta = [
        ("Equipment", report_data.get("equipment", "N/A")),
        ("Analysis Date", datetime.now().strftime("%Y-%m-%d %H:%M")),
        ("Report Type", report_data.get("analysis_type", "General")),
        ("Generated By", "Sovereign AI Workbench"),
        ("Confidence", f"{report_data.get('confidence', 0):.0%}"),
        ("Status", str(report_data.get("recommendation", "PENDING")).split(" - ")[0])
    ]
    for i, (k, v) in enumerate(meta):
        table.rows[i].cells[0].text = k
        table.rows[i].cells[1].text = str(v)
        table.rows[i].cells[0].paragraphs[0].runs[0].bold = True
    
    doc.add_paragraph()
    
    # Findings
    doc.add_heading('Findings', level=1)
    for finding in report_data.get("findings", []):
        doc.add_paragraph(str(finding), style='List Bullet')
    
    # Measurements
    if "measurements" in report_data and report_data["measurements"]:
        doc.add_heading('Measurements', level=1)
        m_table = doc.add_table(rows=1, cols=3, style='Table Grid')
        m_table.rows[0].cells[0].text = "Parameter"
        m_table.rows[0].cells[1].text = "Measured"
        m_table.rows[0].cells[2].text = "Required / Limit"
        for m in report_data["measurements"]:
            row = m_table.add_row()
            row.cells[0].text = str(m.get("parameter", ""))
            row.cells[1].text = str(m.get("measured", ""))
            row.cells[2].text = str(m.get("required", ""))
    
    # Deviations
    if "deviations" in report_data and report_data["deviations"]:
        doc.add_heading('Deviations', level=1)
        for d in report_data["deviations"]:
            p = doc.add_paragraph(style='List Bullet')
            p.add_run(f"{d.get('parameter', 'Deviation')}: ").bold = True
            p.add_run(f"{d.get('deviation', '')} {d.get('unit', '')} ({d.get('status', '')})")
    
    # Recommendations
    doc.add_heading('Recommendations', level=1)
    for rec in report_data.get("recommendations", []):
        doc.add_paragraph(str(rec), style='List Bullet')
    
    # Sources / Citations
    if "citations" in report_data and report_data["citations"]:
        doc.add_heading('Sources', level=1)
        for cite in report_data["citations"]:
            doc.add_paragraph(f"[{cite.get('machine_id', 'MANUAL')}, Page {cite.get('source_page', 1)}] {str(cite.get('text_snippet', ''))[:150]}...", style='List Bullet')
    
    # Footer
    doc.add_paragraph()
    footer = doc.add_paragraph()
    footer.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer.add_run("CONFIDENTIAL - For Internal Use Only").italic = True
    
    # Save
    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    equip = str(report_data.get("equipment", "UNKNOWN")).replace("/", "-")
    filename = f"Analysis_Report_{equip}_{timestamp}.docx"
    output_path = REPORTS_DIR / filename
    doc.save(output_path)
    
    return {
        "report_path": str(output_path),
        "filename": filename,
        "paragraphs": len(doc.paragraphs)
    }

