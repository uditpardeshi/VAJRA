# TOOL 1: Document Reader (PDF/DOCX text extraction)
# ============================================================
async def doc_reader(file_path: str) -> Dict[str, Any]:
    """Extract structured text from PDF/DOCX."""
    path = Path(file_path)
    if not path.exists():
        return {"error": f"File not found: {file_path}"}
    
    text = ""
    if path.suffix.lower() == ".pdf":
        doc = fitz.open(file_path)
        for i, page in enumerate(doc):
            text += f"\n[PAGE {i+1}] {page.get_text()}"
        doc.close()
    elif path.suffix.lower() in (".docx", ".doc"):
        from docx import Document as DocxDocument
        doc = DocxDocument(file_path)
        for i, para in enumerate(doc.paragraphs):
            text += f"\n{para.text}"
    else:
        return {"error": f"Unsupported format: {path.suffix}"}
    
    # Try to extract key-value pairs
    kv_pairs = {}
    for line in text.split("\n"):
        if ":" in line and len(line) < 200:
            parts = line.split(":", 1)
            key = parts[0].strip()
            val = parts[1].strip()
            if key and val:
                kv_pairs[key] = val
    
    return {
        "file_path": file_path,
        "full_text": text[:10000],  # truncate for LLM context
        "extracted_fields": kv_pairs,
        "page_count": max(1, len(text.split("[PAGE ")) - 1)
    }

